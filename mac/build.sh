#!/bin/sh
# Builds ./monitor-input (CLI) and ./MonitorInput.app (menu bar agent; the same binary inside).
# Requires Xcode Command Line Tools:  xcode-select --install
set -e
cd "$(dirname "$0")"
swiftc -O main.swift -o monitor-input -framework IOKit -framework AppKit -framework Carbon -framework ServiceManagement

APP=MonitorInput.app
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp monitor-input "$APP/Contents/MacOS/monitor-input"
cp AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"   # generated by icon/make-icon.swift
cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key><string>com.user.monitor-input</string>
    <key>CFBundleName</key><string>MonitorInput</string>
    <key>CFBundleDisplayName</key><string>Monitor Input</string>
    <key>CFBundleExecutable</key><string>monitor-input</string>
    <key>CFBundleIconFile</key><string>AppIcon</string>
    <key>CFBundlePackageType</key><string>APPL</string>
    <key>CFBundleShortVersionString</key><string>1.0</string>
    <key>CFBundleVersion</key><string>1</string>
    <key>LSMinimumSystemVersion</key><string>14.0</string>
    <key>LSUIElement</key><true/>
</dict>
</plist>
PLIST
# Ad-hoc signature: required on Apple Silicon and binds Info.plist to the bundle (needed for the login item).
codesign --force --sign - "$APP"
echo "Built ./monitor-input and ./$APP"
